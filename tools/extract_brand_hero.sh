#!/usr/bin/env bash
# Rebuilds site/brand-hero.js from the brand book's own 3D engine (canvas 2D + WebGL house, orbit, stage loop).
# Run after editing brand/vault-it-brand-book.html. The line ranges are the engine's sections; check them if the book changes shape:
#   grep -n '3D engine: canvas 2D\|^function makeStage\|^function makeNW\|^var HOUSE=null\|^function popText\|^function flashStage\|^var reduce\|^var \$\$' brand/vault-it-brand-book.html
set -euo pipefail
cd "$(dirname "$0")/.."
B=brand/vault-it-brand-book.html
line() { grep -n "$1" "$B" | head -1 | cut -d: -f1; }
REDUCE=$(line '^var reduce = ');  DD=$(line '^var \$\$ = ')
ENG=$(line '3D engine: canvas 2D'); NW=$(line '^function makeNW'); HOUSEV=$(line '^var HOUSE=null'); HERO=$(line '===== hero: the 3D house builder')
POP=$(line '^function popText'); FLASH=$(line '^function flashStage')
{
  echo '// Vault-It brand hero: the 3D house that builds brick by brick. Copied from brand/vault-it-brand-book.html (its canvas 2D + WebGL engine), no dependencies.'
  echo '// Generated by tools/extract_brand_hero.sh: do not edit by hand, edit the brand book and run the script.'
  echo '// Exposes window.ViBrand = { makeStage, popText, flashStage, tween, rootTheme, reduce, glr }.'
  echo '(function(){'
  sed -n "${REDUCE},${DD}p" "$B"
  sed -n "${ENG},$((NW-1))p" "$B"
  sed -n "${HOUSEV},$((HERO-1))p" "$B"
  sed -n "${POP},${FLASH}p" "$B"
  echo 'window.ViBrand={makeStage:makeStage,popText:popText,flashStage:flashStage,tween:tween,rootTheme:rootTheme,reduce:reduce,glr:glr};'
  echo '})();'
} > site/brand-hero.js
node --check site/brand-hero.js && echo "site/brand-hero.js: $(wc -c < site/brand-hero.js) bytes"
