#!/usr/bin/env node
// Embeds the HB3D engine (src/hb3d) into index.html between the HB3D_ENGINE markers (single-file app).
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..'), SRC = path.join(ROOT, 'src', 'hb3d'), HTML = path.join(ROOT, 'index.html');
const order = ['terraced', 'semi', 'detached', 'mansion', 'flat', 'apartment'];
const parts = [fs.readFileSync(path.join(SRC, 'kit.js'), 'utf8').replace(/\nif \(typeof module !== 'undefined'\) module\.exports = HB3D;\s*$/, '\n')];
order.forEach(m => { const f = path.join(SRC, 'models', m + '.js'); if (fs.existsSync(f)) parts.push(fs.readFileSync(f, 'utf8')); });
parts.push(fs.readFileSync(path.join(SRC, 'viewer.js'), 'utf8'));
const body = parts.join('\n').replace(/<\/script/gi, '<\\/script');
const block = '<script>\n// <<HB3D_ENGINE  (generated by tools/build_hb3d.js from src/hb3d — edit the sources, then rebuild)\n' + body + '\n// HB3D_ENGINE>>\n</script>';
let html = fs.readFileSync(HTML, 'utf8');
const re = /<script>\n\/\/ <<HB3D_ENGINE[\s\S]*?\/\/ HB3D_ENGINE>>\n<\/script>/;
if (re.test(html)) html = html.replace(re, () => block);
else {
  const anchor = '<script src="https://cdn.jsdelivr.net/npm/three@0.128.0/examples/js/controls/OrbitControls.js"></script>';
  if (html.indexOf(anchor) < 0) throw new Error('OrbitControls script tag not found');
  html = html.replace(anchor, anchor + '\n' + block);
}
fs.writeFileSync(HTML, html);
console.log('HB3D engine embedded:', (block.length / 1024).toFixed(1) + ' KB');
