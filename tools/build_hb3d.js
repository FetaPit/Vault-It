#!/usr/bin/env node
// Builds the HB3D engine (src/hb3d) into its app part, src/app/hb3d/engine.generated.html, then rebuilds index.html from
// src/app (tools/build_app.js). The part holds exactly the <script id="hb3d-engine"> block, so never edit it by hand.
const fs = require('fs'), path = require('path');
const ROOT = path.join(__dirname, '..'), SRC = path.join(ROOT, 'src', 'hb3d');
const order = ['terraced', 'semi', 'detached', 'mansion', 'flat', 'apartment'];
const parts = [fs.readFileSync(path.join(SRC, 'kit.js'), 'utf8').replace(/\nif \(typeof module !== 'undefined'\) module\.exports = HB3D;\s*$/, '\n')];
// Only models that load AND build are embedded: a half-written model must never take the whole engine down
// (a type without a model keeps the SVG drawing in the app).
const { execFileSync } = require('child_process');
const skipped = [];
order.forEach(m => {
  const f = path.join(SRC, 'models', m + '.js'); if (!fs.existsSync(f)) return;
  const probe = `var H=require(${JSON.stringify(path.join(SRC, 'kit.js'))});global.HB3D=H;require(${JSON.stringify(f)});` +
    `if(!H.models[${JSON.stringify(m)}]){console.log('placeholder');process.exit(2)}var md=H.build(${JSON.stringify(m)},{});if(!md.instances)process.exit(3);`;
  try { execFileSync(process.execPath, ['-e', probe], { stdio: 'pipe', timeout: 20000 }); parts.push(fs.readFileSync(f, 'utf8')); }
  catch (e) { skipped.push(m + (e.status === 2 ? ' (placeholder)' : ' (' + String(e.stderr || e.message).split('\n').find(l => /Error/.test(l)) + ')')); }
});
if (skipped.length) console.log('Models left out:', skipped.join('; '));
parts.push(fs.readFileSync(path.join(SRC, 'viewer.js'), 'utf8'));
parts.push(fs.readFileSync(path.join(SRC, 'brand.js'), 'utf8'));   // brand look and build animation (house flag)
parts.push(fs.readFileSync(path.join(SRC, 'house_gl.js'), 'utf8').replace(/\nif \(typeof module !== 'undefined'\) module\.exports = HB3D;\s*$/, '\n'));   // v0.7: the house drawn the brand book's way (raw WebGL, no three.js)
const body = parts.join('\n').replace(/<\/script/gi, '<\\/script');
const block = '<script id="hb3d-engine">\n// <<HB3D_ENGINE  (generated by tools/build_hb3d.js from src/hb3d — edit the sources, then rebuild)\n' + body + '\n// HB3D_ENGINE>>\n</script>';
const PART = path.join(ROOT, 'src', 'app', 'hb3d', 'engine.generated.html');
if (!fs.existsSync(PART)) throw new Error('src/app/hb3d/engine.generated.html not found (index.html is built from src/app: docs/APP_SOURCE.md)');
fs.writeFileSync(PART, block + '\n');
require('./build_app').build({ quiet: true });
console.log('HB3D engine embedded:', (block.length / 1024).toFixed(1) + ' KB');
