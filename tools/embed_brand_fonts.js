// Embeds the self-hosted Chakra Petch files (brand/fonts/chakra-petch/*.woff2) into src/app/shell/tokens.css
// as @font-face rules (base64, font-display:swap), between the CHAKRA-FONTS markers. Then run: node tools/build_app.js
// Run: node tools/embed_brand_fonts.js
const fs = require('fs'), path = require('path');
const dir = path.join(__dirname, '..', 'brand', 'fonts', 'chakra-petch');
const css = path.join(__dirname, '..', 'src', 'app', 'shell', 'tokens.css');
const faces = [
  ['Chakra Petch', 300, 'chakra-petch-300.woff2'], ['Chakra Petch', 400, 'chakra-petch-400.woff2'], ['Chakra Petch', 700, 'chakra-petch-700.woff2'],
  ['Chakra Petch Figures', 400, 'chakra-petch-figures-400.woff2'], ['Chakra Petch Figures', 700, 'chakra-petch-figures-700.woff2']];
const out = faces.map(([fam, w, f]) => '@font-face{font-family:"' + fam + '";font-style:normal;font-weight:' + w + ';font-display:swap;src:url(data:font/woff2;base64,' + fs.readFileSync(path.join(dir, f)).toString('base64') + ') format("woff2")}').join('\n');
const A = '/* CHAKRA-FONTS:BEGIN (generated by tools/embed_brand_fonts.js, OFL 1.1) */', B = '/* CHAKRA-FONTS:END */';
let s = fs.readFileSync(css, 'utf8');
const block = A + '\n' + out + '\n' + B;
if (s.includes(A)) s = s.replace(new RegExp(A.replace(/[.*+?^${}()|[\]\\\/]/g, '\\$&') + '[\\s\\S]*?' + B.replace(/[.*+?^${}()|[\]\\\/]/g, '\\$&')), () => block);
else s = s.replace('<style id="vi-tokens">\n', () => '<style id="vi-tokens">\n' + block + '\n');
fs.writeFileSync(css, s); console.log('embedded', faces.length, 'faces,', Math.round(out.length / 1024), 'KB');
