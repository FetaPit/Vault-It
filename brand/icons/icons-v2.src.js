// Coin with a pound sign, used by income and spend.
function poundCoin(cx, cy, r) {
  const s = r / 5.5;
  const x = (v) => r2(cx + v * s), y = (v) => r2(cy + v * s);
  return {
    s: C(cx, cy, r) + P(`M${x(1.6)} ${y(-2.2)}A${r2(1.7 * s)} ${r2(1.7 * s)} 0 0 0 ${x(-1.3)} ${y(-1.3)}V${y(2.4)}M${x(-2.3)} ${y(0.3)}H${x(1)}M${x(-2.3)} ${y(2.4)}H${x(2.2)}`),
    k: C(cx, cy, r),
    d: C(cx, cy, r2(r - 1.2)),
  };
}

