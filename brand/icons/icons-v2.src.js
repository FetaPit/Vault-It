'use strict';

const r2 = (v) => +v.toFixed(2);

// Chamfered rectangle: the pack's futurist corner.
function R(x, y, w, h, c = 1.2) {
  return `<path d="M${r2(x + c)} ${y}H${r2(x + w - c)}L${r2(x + w)} ${r2(y + c)}V${r2(y + h - c)}L${r2(x + w - c)} ${r2(y + h)}H${r2(x + c)}L${x} ${r2(y + h - c)}V${r2(y + c)}Z"/>`;
}
const P = (d) => `<path d="${d}"/>`;
const C = (cx, cy, r) => `<circle cx="${cx}" cy="${cy}" r="${r}"/>`;
const E = (cx, cy, rx, ry) => `<ellipse cx="${cx}" cy="${cy}" rx="${rx}" ry="${ry}"/>`;
const N = (cx, cy, r = 0.7) => C(cx, cy, r);
const pt = (cx, cy, r, a) => [r2(cx + r * Math.cos((a * Math.PI) / 180)), r2(cy + r * Math.sin((a * Math.PI) / 180))];

// Radial ticks from r1 to r2, n of them, starting at angle a0 (degrees, 0 = right, clockwise).
function ticks(cx, cy, ra, rb, n, a0 = -90, skip = []) {
  let d = '';
  for (let i = 0; i < n; i++) {
    if (skip.includes(i)) continue;
    const a = a0 + (360 / n) * i;
    const [x1, y1] = pt(cx, cy, ra, a);
    const [x2, y2] = pt(cx, cy, rb, a);
    d += `M${x1} ${y1}L${x2} ${y2}`;
  }
  return P(d);
}
// Ring segment between radii ra < rb, from angle a1 to a2.
function seg(cx, cy, ra, rb, a1, a2) {
  const [x1, y1] = pt(cx, cy, rb, a1), [x2, y2] = pt(cx, cy, rb, a2);
  const [x3, y3] = pt(cx, cy, ra, a2), [x4, y4] = pt(cx, cy, ra, a1);
  const big = a2 - a1 > 180 ? 1 : 0;
  return P(`M${x1} ${y1}A${rb} ${rb} 0 ${big} 1 ${x2} ${y2}L${x3} ${y3}A${ra} ${ra} 0 ${big} 0 ${x4} ${y4}Z`);
}
// Star polygon, points p, outer ro, inner ri.
function star(cx, cy, ro, ri, p = 5, a0 = -90) {
  let d = '';
  for (let i = 0; i < p * 2; i++) {
    const [x, y] = pt(cx, cy, i % 2 ? ri : ro, a0 + (180 / p) * i);
    d += (i ? 'L' : 'M') + x + ' ' + y;
  }
  return P(d + 'Z');
}
// Dashed circle drawn as arcs, so it needs no dasharray.
function dashRing(cx, cy, r, n = 16, fill = 0.55) {
  let d = '';
  const step = 360 / n;
  for (let i = 0; i < n; i++) {
    const a = -90 + step * i;
    const [x1, y1] = pt(cx, cy, r, a), [x2, y2] = pt(cx, cy, r, a + step * fill);
    d += `M${x1} ${y1}A${r} ${r} 0 0 1 ${x2} ${y2}`;
  }
  return P(d);
}
// Dashed straight line.
function dashLine(x1, y1, x2, y2, n = 6, fill = 0.55) {
  let d = '';
  for (let i = 0; i < n; i++) {
    const t0 = i / n, t1 = (i + fill) / n;
    d += `M${r2(x1 + (x2 - x1) * t0)} ${r2(y1 + (y2 - y1) * t0)}L${r2(x1 + (x2 - x1) * t1)} ${r2(y1 + (y2 - y1) * t1)}`;
  }
  return P(d);
}
// HUD corner brackets inside a box.
function brackets(x, y, w, h, l = 1.6) {
  return P(`M${x} ${y + l}V${y}H${x + l}M${x + w - l} ${y}H${x + w}V${y + l}M${x + w} ${y + h - l}V${y + h}H${x + w - l}M${x + l} ${y + h}H${x}V${y + h - l}`);
}

